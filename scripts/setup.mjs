// Prepares the local Drupal site. Safe to run again: it downloads only what is
// missing, never reinstalls an existing database, and only adds missing seeds.
import { spawnSync } from 'node:child_process';
import { createHash, randomBytes } from 'node:crypto';
import {
  chmodSync,
  copyFileSync,
  existsSync,
  lstatSync,
  mkdirSync,
  readFileSync,
  renameSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  DRUPAL_VERSION,
  databasePath,
  defaultDatabase,
  drupalDir,
  drupalTask,
  passwordFile,
  php,
  root,
  runtimeDir,
} from './runtime.mjs';

const saltFile = join(runtimeDir, 'hash-salt');

function run(command, args, options = {}) {
  const result = spawnSync(command, args, { encoding: 'utf8', maxBuffer: 16 * 1024 * 1024, ...options });
  if (result.error || result.status !== 0)
    throw new Error(`${command} failed: ${result.error?.message ?? ''}${result.stderr}${result.stdout}`);
  return result.stdout;
}

const download = (url, target) => run('curl', ['-fsSL', '--retry', '2', url, '-o', target]);

/** An official FrankenPHP build, verified against GitHub's SHA-256 asset digest. */
function installPhp() {
  if (existsSync(php)) return;
  const os = { darwin: 'mac', linux: 'linux' }[process.platform];
  if (!os) throw new Error('Setup supports macOS and Linux. Place a FrankenPHP binary at .runtime/frankenphp.');
  const arch = process.arch === 'arm64' ? (os === 'mac' ? 'arm64' : 'aarch64') : 'x86_64';
  // 1.13.0 is the last release with an Intel macOS build.
  const tag = os === 'mac' && arch === 'x86_64' ? 'v1.13.0' : 'v1.13.5';
  const asset = `frankenphp-${os}-${arch}`;
  console.log(`Downloading FrankenPHP ${tag} (${asset})…`);
  // CI passes a token: anonymous GitHub API calls share a small hourly limit.
  const auth = process.env.GITHUB_TOKEN ? ['-H', `Authorization: Bearer ${process.env.GITHUB_TOKEN}`] : [];
  const metadata = JSON.parse(
    run('curl', ['-fsSL', ...auth, `https://api.github.com/repos/php/frankenphp/releases/tags/${tag}`]),
  );
  const release = metadata.assets.find((item) => item.name === asset);
  if (!release?.digest?.startsWith('sha256:')) throw new Error(`No ${asset} build with a SHA-256 digest in ${tag}.`);
  const partial = `${php}.download`;
  download(release.browser_download_url, partial);
  const actual = createHash('sha256').update(readFileSync(partial)).digest('hex');
  if (`sha256:${actual}` !== release.digest) {
    rmSync(partial);
    throw new Error('The FrankenPHP download did not match its published checksum.');
  }
  chmodSync(partial, 0o755);
  renameSync(partial, php);
}

function installDrupal() {
  if (existsSync(join(drupalDir, 'autoload.php'))) return;
  const archive = join(runtimeDir, `drupal-${DRUPAL_VERSION}.tar.gz`);
  if (!existsSync(archive)) {
    console.log(`Downloading Drupal ${DRUPAL_VERSION}…`);
    download(`https://ftp.drupal.org/files/projects/drupal-${DRUPAL_VERSION}.tar.gz`, archive);
  }
  run('tar', ['-xzf', archive, '-C', runtimeDir]);
}

/** Links the project's module and theme into the distribution, so edits apply directly. */
function linkExtensions() {
  for (const [source, target] of [
    ['drupal/modules/naturedex_core', 'modules/custom/naturedex_core'],
    ['drupal/themes/naturedex', 'themes/custom/naturedex'],
  ]) {
    const link = join(drupalDir, target);
    mkdirSync(dirname(link), { recursive: true });
    try {
      if (lstatSync(link)) rmSync(link, { recursive: true, force: true });
    } catch {
      /* Nothing there yet. */
    }
    symlinkSync(relative(dirname(link), join(root, source)), link);
  }
}

function writeSettings() {
  const settings = join(drupalDir, 'sites', 'default', 'settings.php');
  if (existsSync(settings)) chmodSync(settings, 0o644);
  if (!existsSync(settings)) copyFileSync(join(drupalDir, 'sites', 'default', 'default.settings.php'), settings);
  const marker = '// NATUREDEX LOCAL SETTINGS';
  const base = readFileSync(settings, 'utf8').split(marker)[0].trimEnd();
  const local = `
${marker}
// Generated by scripts/setup.mjs. Edit that script, not this block.
$databases['default']['default'] = [
  'driver' => 'sqlite',
  'database' => getenv('NATUREDEX_DB') ?: ${JSON.stringify(defaultDatabase)},
  'namespace' => 'Drupal\\\\sqlite\\\\Driver\\\\Database\\\\sqlite',
  'autoload' => 'core/modules/sqlite/src/Driver/Database/sqlite/',
];
$settings['hash_salt'] = trim(file_get_contents(${JSON.stringify(saltFile)}));
$settings['trusted_host_patterns'] = ['^127\\\\.0\\\\.0\\\\.1$', '^localhost$'];
$settings['config_sync_directory'] = ${JSON.stringify(join(runtimeDir, 'config-sync'))};
$settings['file_private_path'] = ${JSON.stringify(join(runtimeDir, 'private-files'))};
$settings['update_free_access'] = FALSE;
$settings['container_yamls'][] = ${JSON.stringify(join(root, 'drupal', 'local.services.yml'))};
// Production sets 300 seconds; the browser tests use the same value.
$config['system.performance']['cache']['page']['max_age'] = (int) getenv('NATUREDEX_PAGE_MAX_AGE');
$config['system.logging']['error_level'] = getenv('NATUREDEX_SHOW_ERRORS') ? 'verbose' : 'hide';
`;
  writeFileSync(settings, `${base}\n${local}`);
}

/** Installs through scripts/drupal-task.php, the same code path production uses. */
function installSite() {
  const database = databasePath();
  if (existsSync(database)) return false;
  mkdirSync(dirname(database), { recursive: true });
  console.log('Installing Drupal with SQLite…');
  drupalTask(['install'], { env: { NATUREDEX_ADMIN_PASSWORD: readFileSync(passwordFile, 'utf8').trim() } });
  return true;
}

export function setup() {
  mkdirSync(join(runtimeDir, 'data'), { recursive: true });
  if (!existsSync(passwordFile))
    writeFileSync(passwordFile, `${randomBytes(18).toString('base64url')}\n`, { mode: 0o600 });
  if (!existsSync(saltFile)) writeFileSync(saltFile, `${randomBytes(48).toString('base64url')}\n`, { mode: 0o600 });
  installPhp();
  installDrupal();
  linkExtensions();
  // Drupal's installer write-protects these; setup owns them.
  chmodSync(join(drupalDir, 'sites', 'default'), 0o755);
  writeSettings();
  const fresh = installSite();
  drupalTask(['setup']);
  if (fresh) console.log(`Sign in at /user/login as admin; the password is in ${relative(root, passwordFile)}.`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    setup();
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
